"""The Stats step and what Install does with it: the item rows read back from the item SQL, one UPDATE
per piece, item sets in an ItemSet table and inside an MPQ."""

from retroport.dbc import DBCFile
from retroport.mpq import MPQ, add_files, write_archive
from retroport.workbench import itemstats as I

ITEM_SQL = """-- generated by Retroport Workbench; retail 12.1.5.70391
-- items are cosmetic copies: any class, any race, level 1, no stats
DELETE FROM `item_template` WHERE `entry` IN (900000,900001,900002);
INSERT INTO `item_template` (`entry`,`class`,`subclass`,`SoundOverrideSubclass`,`name`,`displayid`,`Quality`,`InventoryType`,`AllowableClass`,`AllowableRace`,`ItemLevel`,`RequiredLevel`,`Material`,`sheath`,`bonding`,`stackable`,`MaxDurability`) VALUES
(900000,2,13,-1,'Gara''kal, Fist of the Spiritbinder',225000,4,13,-1,-1,1,0,1,7,0,1,0),
(900001,4,2,-1,'Banded Poncho (Heroic)',225001,4,5,-1,-1,1,0,8,0,0,1,0),
(900002,4,1,-1,'Silken Drape',225002,4,16,-1,-1,1,0,7,0,0,1,0);
"""
IDS = {"display": {"10": 225000, "11": 225001, "12": 225002}, "item": {"10": 900000, "11": 900001, "12": 900002}}


def test_the_item_rows_are_read_back_from_the_sql():
    rows = I.kit_items(ITEM_SQL)
    assert sorted(rows) == [900000, 900001, 900002]
    assert rows[900000]["name"] == "Gara'kal, Fist of the Spiritbinder" and rows[900001]["subclass"] == 2
    assert rows[900002]["InventoryType"] == 16


def test_a_piece_takes_every_pieces_values_unless_it_has_its_own():
    edits = {"global": {"ilvl": 264, "classes": 8}, "pieces": {"11": {"ilvl": 277, "classes": ""}}, "sets": []}
    assert I.effective(edits, "11", "ilvl") == 277 and I.effective(edits, "10", "ilvl") == 264
    assert I.effective(edits, "11", "classes") == 8                       # "" is "not set": the global value
    assert I.touched(edits, "12") and not I.touched(I.empty(), "12")


def test_each_basket_set_has_its_own_values_and_a_broken_one_lets_each_piece_set_its_own():
    plan = {"entries": [{"kind": "set", "key": "set:a", "looks": [{"display": 10}, {"display": 11}]},
                        {"kind": "set", "key": "set:b", "looks": [{"display": 11}, {"display": 12}]},
                        {"kind": "item", "key": "item:c", "looks": [{"display": 13}]}]}
    groups = I.groups_of(plan)
    assert groups == {"10": "set:a", "11": "set:a", "12": "set:b"}           # a shared look: its first set's; an item: none
    edits = {"global": {"ilvl": 200, "quality": 3, "armor_type": 2},
             "groups": {"set:a": {"ilvl": 264, "armor_type": 4}, "set:b": {"ilvl": 277, "broken": True}},
             "pieces": {"10": {"ilvl": 300, "armor_type": 3}, "12": {"ilvl": 284}, "13": {"ilvl": 250}}, "sets": []}
    eff = lambda d, f: I.effective(edits, d, f, group=groups.get(d))     # noqa: E731
    assert eff("10", "ilvl") == 264 and eff("11", "ilvl") == 264        # a whole set: the set's, not the piece's own
    assert eff("10", "armor_type") == 3 and eff("11", "armor_type") == 4  # armor type: still a piece's own
    assert eff("12", "ilvl") == 284 and eff("12", "armor_type") == 2     # broken: its own, else the basket's
    assert eff("13", "ilvl") == 250 and eff("13", "quality") == 3        # an item of its own: its own, else the basket's
    rows = {900000 + k: {"entry": 900000 + k, "class": 4, "subclass": 1, "InventoryType": 5, "name": f"P{k}"} for k in range(4)}
    ids = {"item": {str(10 + k): 900000 + k for k in range(4)}}
    ups = {int(line.rsplit("= ", 1)[1].rstrip(";")): line for line in I.updates(edits, ids, rows, {}, groups=groups)}
    assert "`ItemLevel` = 264" in ups[900000] and "`ItemLevel` = 264" in ups[900001]
    assert "`ItemLevel` = 284" in ups[900002] and "`ItemLevel` = 250" in ups[900003]
    assert "`subclass` = 3" in ups[900000] and "`subclass` = 4" in ups[900001]


