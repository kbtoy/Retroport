def test_the_stats_become_one_update_per_piece():
    edits = {"global": {"ilvl": 264, "req": 80, "quality": 4, "armor_type": 4, "classes": 1535},
             "pieces": {"10": {"stats": [[38, 93], [3, 69]], "dmg_min": 326, "dmg_max": 490, "delay": 1800, "durability": 75},
                        "11": {"stats": [[4, 169], [7, 185], [32, 108]], "armor": 2641, "sockets": [2, 4], "socket_bonus": 3357,
                               "name": "Poncho of O'Neil", "unique": True, "sell": 25},
                        "12": {"armor": 177}},
             "sets": [{"key": "a", "name": "Test Set", "pieces": ["11", "12"], "bonuses": [[2, 70761]]}]}
    lines = I.updates(edits, IDS, I.kit_items(ITEM_SQL), {"a": 3000})
    ups = {int(l.rsplit("= ", 1)[1].rstrip(";")): l for l in lines}
    assert sorted(ups) == [900000, 900001, 900002]
    w, chest, cloak = ups[900000], ups[900001], ups[900002]
    assert "`dmg_min1` = 326, `dmg_max1` = 490" in w and "`delay` = 1800" in w and "`subclass`" not in w   # a weapon keeps its type
    assert "`AllowableClass` = -1" in w                                     # every class is "any class"
    assert "`subclass` = 4, `Material` = 6" in chest and "`stat_type1` = 4, `stat_value1` = 169" in chest
    assert "`name` = 'Poncho of O''Neil'" in chest and "`maxcount` = 1" in chest and "`BuyPrice` = 100" in chest
    assert "`socketColor_1` = 2, `socketContent_1` = 0, `socketColor_2` = 4" in chest and "`socketBonus` = 3357" in chest
    assert "`itemset` = 3000" in chest and "`itemset` = 3000" in cloak
    assert "`subclass`" not in cloak                                        # a cloak is cloth whatever the set is


def _itemset_table(*ids) -> bytes:
    t = DBCFile(53)
    for i in ids:
        t.add_record([i, t.add_string(f"Set {i}")] + [0] * 15 + [0x00FF01FE] + [0] * 35)
    return t.to_bytes()


def test_item_sets_are_added_to_an_itemset_table_and_replaced_not_doubled(tmp_path):
    sids = I.set_ids(str(tmp_path), [{"key": "a"}, {"key": "b"}])
    assert sids == {"a": 3000, "b": 3001} and I.set_ids(str(tmp_path), [{"key": "b"}]) == sids     # kept
    edits = {"sets": [{"key": "a", "name": "Test Set", "pieces": ["11", "12", "99"], "bonuses": [[4, 7], [2, 5]]}]}
    rows = I.set_rows(edits, IDS, sids)
    assert rows == [{"id": 3000, "name": "Test Set", "items": [900001, 900002], "bonuses": [(2, 5), (4, 7)]}]
    once = I.itemset_dbc(_itemset_table(1, 901), rows, set(sids.values()))
    twice = I.itemset_dbc(once, rows, set(sids.values()))
    t = DBCFile.from_bytes(twice)
    assert [r[0] for r in t.records] == [1, 901, 3000] and once == twice
    r = t.find_by_id(3000)
    assert t.get_string(r[1]) == "Test Set" and r[17] == 0x00FF01FE and r[18:20] == [900001, 900002]
    assert r[35:37] == [5, 7] and r[43:45] == [2, 4]
    gone = DBCFile.from_bytes(I.itemset_dbc(twice, [], set(sids.values())))
    assert [r[0] for r in gone.records] == [1, 901]                         # a set taken away leaves no row


def test_a_file_goes_into_an_existing_archive_and_the_rest_reads_as_before(tmp_path):
    p = str(tmp_path / "patch-I.MPQ")
    write_archive(p, {"DBFilesClient\\Item.dbc": b"ITEM" * 300, "Item\\Objects\\x.m2": bytes(range(256)) * 40})
    add_files(p, {"DBFilesClient\\ItemSet.dbc": b"SETS" * 2000})
    add_files(p, {"DBFilesClient\\ItemSet.dbc": b"NEWER"})                  # again: the name points at the new copy
    m = MPQ(p)
    try:
        assert m.read("DBFilesClient\\Item.dbc") == b"ITEM" * 300 and m.read("Item\\Objects\\x.m2") == bytes(range(256)) * 40
        assert m.read("DBFilesClient\\ItemSet.dbc") == b"NEWER"
        assert m.read("(listfile)").decode("latin-1").split("\r\n").count("DBFilesClient\\ItemSet.dbc") == 1
    finally:
        m.close()


