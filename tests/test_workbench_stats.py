def test_the_wotlk_reference_measures_real_items():
    from retroport.workbench import wotlk as W

    def sparse(i, name, ilvl, inv, armor, dur, stats=()):
        stat_t = [t for t, _v in stats] + [-1] * (10 - len(stats))
        stat_v = [v for _t, v in stats] + [0] * (10 - len(stats))
        return {"ID": i, "Display_lang": name, "ItemLevel": ilvl, "RequiredLevel": 80, "OverallQualityID": 4,
                "InventoryType": inv, "StatModifier_bonusStat": stat_t, "StatModifier_bonusAmount": stat_v,
                "SocketType": [2, 0, 0], "Socket_match_enchantment_ID": 3357, "Resistances": [armor, 0, 0, 0, 0, 0, 0],
                "MinDamage": [0] * 5, "MaxDamage": [0] * 5, "ItemDelay": 0, "MaxDurability": dur, "SellPrice": 100,
                "Bonding": 1, "AllowableClass": -1, "ItemSet": 0}

    class Fake:
        tables = {
            "Item": [(i, {"ID": i, "ClassID": 4, "SubclassID": 4, "Material": 6}) for i in (1, 2, 3)],
            "ItemSparse": [(1, sparse(1, "Battleplate A", 251, 5, 2526, 165, [(4, 148), (7, 164)])),
                           (2, sparse(2, "Battleplate B", 264, 5, 2641, 165, [(4, 169), (7, 185)])),
                           (3, sparse(3, "Battleplate C", 264, 5, 2641, 165))],
            "RandPropPoints": [(264, {"ID": 264, "Epic": [308, 229, 172, 132, 97], "Superior": [0] * 5, "Good": [0] * 5})],
            "ItemDamageTwoHand": [(264, {"ItemLevel": 264, "Quality": [0, 0, 0, 0, 294.79, 294.79, 294.79]})],
        }

        def table(self, name):
            if name not in self.tables:
                raise LookupError(name)
            return self.tables[name]
    ref = W.build(Fake())
    assert ref["armor"]["4:4:5:4"] == [[251, 2526], [264, 2641]] and ref["durability"]["4:4:5:4"] == 165
    assert ref["rpp"][264][0] == 308 and ref["dps"]["ItemDamageTwoHand"][264][4] == 294.79
    hits = W.search(ref, "battleplate", inv=20)                               # a robe asks: a chest answers
    assert [h["name"] for h in hits] == ["Battleplate B", "Battleplate C", "Battleplate A"]
    assert hits[0]["stats"] == [[4, 169], [7, 185]] and hits[0]["sockets"] == [2]


def test_every_value_stays_inside_its_azerothcore_column():
    kit = {900032: {"entry": 900032, "class": 2, "subclass": 8, "InventoryType": 17, "name": "Preyseeker's Falchion"}}
    edits = {"global": {}, "pieces": {"715489": {"sell": 9999999990000, "durability": 99999, "stats": [[7, 3000]],
                                                 "dmg_min": 3500, "dmg_max": 5500, "delay": 1500}}, "sets": []}
    sql = I.updates(edits, {"item": {"715489": 900032}}, kit, {})[0]
    assert "StatsCount" not in sql                               # AzerothCore counts the stats it loads
    assert "`SellPrice` = 4294967295" in sql and "`BuyPrice` = 2147483647" in sql
    assert "`MaxDurability` = 65535" in sql and "`stat_value1` = 3000" in sql and "`delay` = 1500" in sql
    assert I.column_value("Quality", 9) == 7 and I.column_value("name", "'x'") == "'x'"


def test_levels_quality_and_binding_of_a_piece_in_a_whole_set_are_the_sets():
    kit = {900001: {"entry": 900001, "class": 4, "subclass": 1, "InventoryType": 1, "name": "Hood"}}
    edits = {"global": {"ilvl": 277, "quality": 4}, "pieces": {"5": {"ilvl": 264, "quality": 3, "stats": [[7, 10]]}}, "sets": []}
    sql = I.updates(edits, {"item": {"5": 900001}}, kit, {}, groups={"5": "set:a"})[0]
    assert "`ItemLevel` = 277" in sql and "`Quality` = 4" in sql          # the set has none: the basket's
    edits["groups"] = {"set:a": {"broken": True}}
    sql = I.updates(edits, {"item": {"5": 900001}}, kit, {}, groups={"5": "set:a"})[0]
    assert "`ItemLevel` = 264" in sql and "`Quality` = 3" in sql          # broken: the piece's own


