"""AzerothCore world-database SQL for a new playable race, plus the matching undo.

Everything mirrors the faction template race (``RaceSpec.template``):

* per-race rows are copied: ``playercreateinfo`` (start position, every class the
  template has - all ten with ARAC), ``playercreateinfo_action``, ``playercreateinfo_item``,
  ``player_race_stats``;
* every race mask that includes the template gains the new race's bit:
  ``playercreateinfo_skills`` (languages, racial and weapon skills),
  ``playercreateinfo_spell_custom``, ``playercreateinfo_cast_spell``, ``quest_template``
  (faction quests), ``item_template`` (faction items), ``spell_area``, ``mail_level_reward``
  and race ``conditions`` (type 16);
* ``creature_model_info`` rows for the new displays copy the look template's.

The script deletes its own per-race rows first, so it can be re-applied after a rebuild.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from .tables import RaceSpec

ALL_RACE_MASKS = "4294967295, 2147483647"
# AzerothCore (SpellMgr.h): the proc flags whose events have a spell phase - the owner's own
# spells and hits (REQ_SPELL_PHASE_PROC_FLAG_MASK); PROC_SPELL_PHASE_HIT
REQ_SPELL_PHASE_FLAGS = 0x10 | 0x40 | 0x100 | 0x400 | 0x1000 | 0x4000 | 0x10000 | 0x40000 | 0x200000
PROC_PHASE_HIT = 2


@dataclass
class RacialSql:
    """A race's own racials (racials.py) on the server."""
    skill_line: int                                       # its racial skill line
    name: str                                             # "Racial - Kul Tiran"
    excluded_skills: list[int]                            # 3.3.5's racial lines, not copied from the template
    ap_bonus: dict[int, float] = field(default_factory=dict)      # spell -> spell_bonus_data.ap_bonus
    sp_bonus: dict[int, float] = field(default_factory=dict)      # spell -> spell_bonus_data.direct_bonus
    scripts: dict[int, str] = field(default_factory=dict)         # spell -> spell_script_names.ScriptName
    procs: dict[int, int] = field(default_factory=dict)           # scripted spell -> its proc flags (spell_proc)
    no_bonus: list[int] = field(default_factory=list)             # spells whose amount a script sets
    old_spells: list[int] = field(default_factory=list)           # the racial spells of 3.3.5's racial lines
    bound: dict[str, list[int]] = field(default_factory=dict)     # ScriptName -> other spells it goes on
    pet_auras: list[tuple[int, int, int]] = field(default_factory=list)   # (spell, its dummy effect, pet spell)


@dataclass
class StartItem:
    """One piece of a race's own start outfit (items.py) as an item_template row."""
    entry: int                                            # item and display id
    name: str
    subclass: int                                         # armour: 1 cloth .. 4 plate
    material: int
    inventory_type: int
    armor: int
    durability: int
    item_class: int = 4                                   # 4 armour, 2 weapon
    sheath: int = 0
    dmg_min: int = 0                                      # a weapon's damage, speed (ms), what it shoots
    dmg_max: int = 0
    delay: int = 0
    ammo_type: int = 0
    ranged_mod_range: int = 0
    block: int = 0                                        # a shield's

    @property
    def held(self) -> bool:
        return self.item_class != 4 or self.inventory_type in (14, 23)


def _sql_text(s: str) -> str:
    return s.replace("\\", "\\\\").replace("'", "\\'")

MASK_UPDATES = [
    ("playercreateinfo_skills", "raceMask", ""),
    ("playercreateinfo_spell_custom", "racemask", ""),
    ("playercreateinfo_cast_spell", "raceMask", ""),
    ("quest_template", "AllowableRaces", ""),
    ("item_template", "AllowableRace", " AND `AllowableRace` > 0"),
    ("spell_area", "racemask", ""),
    ("mail_level_reward", "raceMask", ""),
    ("conditions", "ConditionValue1", " AND `ConditionTypeOrReference` = 16"),
]
COPY_TABLES = [
    ("playercreateinfo", "`race`, `class`, `map`, `zone`, `position_x`, `position_y`, `position_z`, `orientation`"),
    ("playercreateinfo_action", "`race`, `class`, `button`, `action`, `type`"),
    ("playercreateinfo_item", "`race`, `class`, `itemid`, `amount`, `Note`"),
]


def race_sql(specs: list[RaceSpec], name: str, displays: dict[int, int],
             racial: RacialSql | None = None, start_items: list[StartItem] | None = None) -> tuple[str, str]:
    """(install, undo) SQL. ``displays`` maps each new display id -> the template display it copies.
    With ``racial`` the race learns its own racial skill line instead of its template's; with
    ``start_items`` its start outfits' own armour exists (white, item level 1, as 3.3.5's is)."""
    excluded = ", ".join(str(k) for k in racial.excluded_skills) if racial else ""
    out = [f"-- {name}: playable race rows for AzerothCore (world database), generated by retroport.",
           "-- Apply after copying the server DBCs; re-applying is safe. Undo: the matching *_undo.sql.", ""]
    undo = [f"-- Removes what the {name} install SQL added.", ""]
    for s in specs:
        out += [f"-- ---- race {s.race_id} ({s.faction}), copied from race {s.template}",
                f"SET @RACE := {s.race_id}, @TEMPLATE := {s.template}, "
                f"@BIT := {s.bit}, @TEMPLATE_BIT := {s.template_bit};"]
        undo += [f"-- ---- race {s.race_id}", f"SET @RACE := {s.race_id}, @BIT := {s.bit};"]
        for table, cols in COPY_TABLES:
            rest = cols.split(", ", 1)[1]
            out += [f"DELETE FROM `{table}` WHERE `race` = @RACE;",
                    f"INSERT INTO `{table}` ({cols}) SELECT @RACE, {rest} FROM `{table}` WHERE `race` = @TEMPLATE;"]
            undo.append(f"DELETE FROM `{table}` WHERE `race` = @RACE;")
        out += ["DELETE FROM `player_race_stats` WHERE `Race` = @RACE;",
                "INSERT INTO `player_race_stats` (`Race`, `Strength`, `Agility`, `Stamina`, `Intellect`, `Spirit`) "
                "SELECT @RACE, `Strength`, `Agility`, `Stamina`, `Intellect`, `Spirit` FROM `player_race_stats` "
                "WHERE `Race` = @TEMPLATE;"]
        undo.append("DELETE FROM `player_race_stats` WHERE `Race` = @RACE;")
        for table, col, extra in MASK_UPDATES:
            if racial and table == "playercreateinfo_skills" and excluded:
                # the template's racial skill is not the race's: none for it (one an earlier install gave goes)
                out.append(f"UPDATE `{table}` SET `{col}` = `{col}` & ~@BIT WHERE `skill` IN ({excluded}) "
                           f"AND `{col}` & @BIT AND `{col}` NOT IN ({ALL_RACE_MASKS});")
                extra = f" AND `skill` NOT IN ({excluded})"
            out.append(f"UPDATE `{table}` SET `{col}` = `{col}` | @BIT "
                       f"WHERE `{col}` & @TEMPLATE_BIT AND NOT `{col}` & @BIT{extra};")
            undo.append(f"UPDATE `{table}` SET `{col}` = `{col}` & ~@BIT "
                        f"WHERE `{col}` & @BIT AND `{col}` NOT IN (4294967295, 2147483647){extra};")
        out.append("")
        undo.append("")
    if racial:
        mask = 0
        for s in specs:
            mask |= s.bit
        lines, undo_lines = racial_sql_lines(racial, mask)
        out += lines
        undo += undo_lines
    if start_items:
        ids = ", ".join(str(i.entry) for i in start_items)
        out += ["-- its own start outfits (BfA's armour and weapons): new characters get them through CharStartOutfit.dbc",
                f"DELETE FROM `item_template` WHERE `entry` IN ({ids});"]
        out += ["INSERT INTO `item_template` (`entry`, `class`, `subclass`, `SoundOverrideSubclass`, `name`, `displayid`, "
                "`Quality`, `BuyPrice`, `SellPrice`, `InventoryType`, `AllowableClass`, `AllowableRace`, `ItemLevel`, "
                "`RequiredLevel`, `stackable`, `armor`, `Material`, `MaxDurability`) VALUES "
                f"({i.entry}, 4, {i.subclass}, -1, '{_sql_text(i.name)}', {i.entry}, 1, 5, 1, {i.inventory_type}, -1, -1, "
                f"1, 1, 1, {i.armor}, {i.material}, {i.durability});" for i in start_items if not i.held]
        # weapons, shields and off-hands: 3.3.5's own start weapons' damage and speed, sheathed as BfA's
        out += ["INSERT INTO `item_template` (`entry`, `class`, `subclass`, `SoundOverrideSubclass`, `name`, `displayid`, "
                "`Quality`, `BuyPrice`, `SellPrice`, `InventoryType`, `AllowableClass`, `AllowableRace`, `ItemLevel`, "
                "`RequiredLevel`, `stackable`, `dmg_min1`, `dmg_max1`, `dmg_type1`, `armor`, `delay`, `ammo_type`, "
                "`RangedModRange`, `Material`, `sheath`, `block`, `MaxDurability`) VALUES "
                f"({i.entry}, {i.item_class}, {i.subclass}, -1, '{_sql_text(i.name)}', {i.entry}, 1, 5, 1, "
                f"{i.inventory_type}, -1, -1, 1, 1, 1, {i.dmg_min}, {i.dmg_max}, 0, {i.armor}, {i.delay}, {i.ammo_type}, "
                f"{i.ranged_mod_range}, {i.material}, {i.sheath}, {i.block}, {i.durability});"
                for i in start_items if i.held]
        out.append("")
        undo.append(f"DELETE FROM `item_template` WHERE `entry` IN ({ids});")
    if displays:
        ids = ", ".join(str(d) for d in displays)
        out += ["-- base displays (bounding radius / combat reach copied from the template race's)",
                f"DELETE FROM `creature_model_info` WHERE `DisplayID` IN ({ids});"]
        for new, tpl in displays.items():
            out.append("INSERT INTO `creature_model_info` (`DisplayID`, `BoundingRadius`, `CombatReach`, `Gender`, "
                       f"`DisplayID_Other_Gender`) SELECT {new}, `BoundingRadius`, `CombatReach`, `Gender`, 0 "
                       f"FROM `creature_model_info` WHERE `DisplayID` = {tpl};")
        undo.append(f"DELETE FROM `creature_model_info` WHERE `DisplayID` IN ({ids});")
    return "\n".join(out) + "\n", "\n".join(undo) + "\n"


def racial_sql_lines(racial: RacialSql, race_mask: int) -> tuple[list[str], list[str]]:
    """(install, undo) lines that give the races of ``race_mask`` (0: every race the line's
    SkillRaceClassInfo rows let have it - a registry race past 32, race/identity.py) their own
    racial skill line and its spells' server rows."""
    out: list[str] = []
    undo: list[str] = []
    out += [f"-- its own racials: {racial.name} (skill line {racial.skill_line})",
            f"DELETE FROM `playercreateinfo_skills` WHERE `skill` = {racial.skill_line};",
            "INSERT INTO `playercreateinfo_skills` (`raceMask`, `classMask`, `skill`, `rank`, `comment`) VALUES "
            f"({race_mask}, 0, {racial.skill_line}, 0, '{_sql_text(racial.name)}');"]
    undo.append(f"DELETE FROM `playercreateinfo_skills` WHERE `skill` = {racial.skill_line};")
    bonus = sorted(set(racial.ap_bonus) | set(racial.sp_bonus))
    if bonus:
        ids = ", ".join(str(k) for k in bonus)
        out += [f"DELETE FROM `spell_bonus_data` WHERE `entry` IN ({ids});"]
        out += [f"INSERT INTO `spell_bonus_data` (`entry`, `direct_bonus`, `dot_bonus`, `ap_bonus`, `ap_dot_bonus`, "
                f"`comments`) VALUES ({k}, {racial.sp_bonus.get(k, 0):g}, 0, {racial.ap_bonus.get(k, 0):g}, 0, "
                f"'{_sql_text(racial.name)}');" for k in bonus]
        undo.append(f"DELETE FROM `spell_bonus_data` WHERE `entry` IN ({ids});")
    if racial.no_bonus:
        ids = ", ".join(str(k) for k in racial.no_bonus)
        out += [f"DELETE FROM `spell_bonus_data` WHERE `entry` IN ({ids});"]
        out += [f"INSERT INTO `spell_bonus_data` (`entry`, `direct_bonus`, `dot_bonus`, `ap_bonus`, `ap_dot_bonus`, "
                f"`comments`) VALUES ({k}, 0, 0, 0, 0, '{_sql_text(racial.name)}: amount set by script');"
                for k in racial.no_bonus]
        undo.append(f"DELETE FROM `spell_bonus_data` WHERE `entry` IN ({ids});")
    if racial.scripts:
        ids = ", ".join(str(k) for k in racial.scripts)
        out += ["-- needs the AzerothCore module mod-retroport-racials (retroport-tool\\native)",
                f"DELETE FROM `spell_script_names` WHERE `spell_id` IN ({ids});"]
        out += [f"INSERT INTO `spell_script_names` (`spell_id`, `ScriptName`) VALUES ({k}, '{v}');"
                for k, v in racial.scripts.items()]
        undo.append(f"DELETE FROM `spell_script_names` WHERE `spell_id` IN ({ids});")
    if racial.procs:
        ids = ", ".join(str(k) for k in racial.procs)
        out += [f"DELETE FROM `spell_proc` WHERE `SpellId` IN ({ids});"]
        # BfA's flags, on damage; on hit for a spell the owner casts (AzerothCore checks the
        # phase for those only, and warns about one given for anything else)
        out += ["INSERT INTO `spell_proc` (`SpellId`, `ProcFlags`, `SpellTypeMask`, `SpellPhaseMask`, `Chance`) "
                f"VALUES ({k}, {v}, 1, {PROC_PHASE_HIT if v & REQ_SPELL_PHASE_FLAGS else 0}, 100);"
                for k, v in racial.procs.items()]
        undo.append(f"DELETE FROM `spell_proc` WHERE `SpellId` IN ({ids});")
    for script, spells in racial.bound.items():
        out += [f"-- {script} on the spells a racial changes (mod-retroport-racials)",
                f"DELETE FROM `spell_script_names` WHERE `ScriptName` = '{script}';"]
        if spells:
            out.append("INSERT INTO `spell_script_names` (`spell_id`, `ScriptName`) VALUES "
                       + ", ".join(f"({s}, '{script}')" for s in spells) + ";")
        undo.append(f"DELETE FROM `spell_script_names` WHERE `ScriptName` = '{script}';")
    if racial.pet_auras:
        # AzerothCore casts the pet spell on every permanent pet while the racial's dummy aura is on
        ids = ", ".join(str(k) for k in sorted({s for s, _e, _a in racial.pet_auras}))
        out += ["-- what its racials give the pet (AzerothCore's spell_pet_auras; pet 0 = every pet)",
                f"DELETE FROM `spell_pet_auras` WHERE `spell` IN ({ids});",
                "INSERT INTO `spell_pet_auras` (`spell`, `effectId`, `pet`, `aura`) VALUES "
                + ", ".join(f"({s}, {e}, 0, {a})" for s, e, a in racial.pet_auras) + ";"]
        undo.append(f"DELETE FROM `spell_pet_auras` WHERE `spell` IN ({ids});")
    out.append("")
    return out, undo


def characters_cleanup_sql(specs: list[RaceSpec], name: str, racial: RacialSql) -> str:
    """For the characters database (optional): existing characters of the race forget the racial
    spells they learned from their template's racial skill line before the race had its own.
    AzerothCore deletes that skill at login but keeps the spells."""
    races = ", ".join(str(s.race_id) for s in specs)
    spells = ", ".join(str(k) for k in sorted(set(racial.old_spells)))
    return "\n".join([
        f"-- {name}: optional cleanup for the CHARACTERS database, generated by retroport.",
        f"-- Existing characters of races {races} keep the template race's racial spells they learned before",
        f"-- the race had its own ({racial.name}); this removes them. New characters never get them.",
        "DELETE `cs` FROM `character_spell` `cs` JOIN `characters` `c` ON `c`.`guid` = `cs`.`guid`",
        f"WHERE `c`.`race` IN ({races}) AND `cs`.`spell` IN ({spells});",
        "DELETE `ca` FROM `character_aura` `ca` JOIN `characters` `c` ON `c`.`guid` = `ca`.`guid`",
        f"WHERE `c`.`race` IN ({races}) AND `ca`.`spell` IN ({spells});",
        ""])
